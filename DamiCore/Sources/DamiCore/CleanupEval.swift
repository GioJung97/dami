import Foundation

/// Runs the real pipeline over `bench/cleanup_cases.tsv`.
public enum CleanupEval {
    public struct Case: Equatable, Sendable {
        public var id, language, category, input, expectedLight, notes: String
        /// Right answers for Smart, separated by ` || ` (v0.4 M2).
        public var expectedSmart = ""

        public init(
            id: String, language: String, category: String, input: String, expectedLight: String, notes: String, expectedSmart: String = ""
        ) {
            self.id = id
            self.language = language
            self.category = category
            self.input = input
            self.expectedLight = expectedLight
            self.notes = notes
            self.expectedSmart = expectedSmart
        }
    }

    public struct Result: Equatable, Sendable {
        public var testCase: Case
        public var output: String
        public var passed: Bool { output == testCase.expectedLight }
        /// A case rules leave alone by design, marked in its notes.
        public var isDeliberatelyUnfixed: Bool { testCase.notes.hasPrefix("by design") }
    }

    /// Columns: id, lang, category, input, expected_light, notes, expected_smart.
    public static func parse(_ tsv: String) -> [Case] {
        tsv.split(whereSeparator: \.isNewline).dropFirst().compactMap { line in
            let columns = line.split(separator: "\t", omittingEmptySubsequences: false).map(String.init)
            guard columns.count >= 6 else { return nil }
            return Case(
                id: columns[0], language: columns[1], category: columns[2], input: columns[3], expectedLight: columns[4], notes: columns[5],
                expectedSmart: columns.count > 6 ? columns[6] : ""
            )
        }
    }

    public static func run(_ cases: [Case]) -> [Result] {
        cases.map { testCase in
            // Mixed sentences are detected as the second language.
            let language = testCase.language == "mixed" ? "ko" : testCase.language
            let processed = TextPipeline.process(raw: testCase.input, mode: .light, language: language, rules: [])
            return Result(testCase: testCase, output: processed.final)
        }
    }

    public static func report(_ results: [Result]) -> String {
        let keep = results.filter { $0.testCase.category == "must_keep" }
        let fix = results.filter { $0.testCase.category == "must_fix" }
        let attempted = fix.filter { !$0.isDeliberatelyUnfixed }
        let byDesign = fix.filter(\.isDeliberatelyUnfixed)
        let smartTargets = results.filter { SmartScore.isTarget($0.testCase) }
        let lightOnSmart = smartTargets.filter { SmartScore.matches($0.output, $0.testCase) }.count
        var lines = [
            "# Cleanup rules: eval results",
            "",
            "Generated by `dami-eval` from `bench/cleanup_cases.tsv`. Light mode, no Dictionary rules.",
            "",
            "- `must_keep`: \(keep.filter(\.passed).count) of \(keep.count) unchanged",
            "- `must_fix`: \(attempted.filter(\.passed).count) of \(attempted.count) fixed",
            "- `must_fix` left alone by design: \(byDesign.count)",
            "- Smart target cases: Light already matches `expected_smart` in \(lightOnSmart) of \(smartTargets.count). Smart has to reach "
                + "\(lightOnSmart + SmartScore.marginOverLight) (`docs/plans/v0.4.md` §4.2)",
            "",
        ]
        func table(_ title: String, _ rows: [Result], output: Bool = true) {
            lines += ["## \(title)", ""]
            guard !rows.isEmpty else {
                lines += ["None.", ""]
                return
            }
            lines += ["| id | input | output | expected |", "|---|---|---|---|"]
            lines += rows.map { "| \($0.testCase.id) | \(cell($0.testCase.input)) | \(cell($0.output)) | \(cell($0.testCase.expectedLight)) |" }
            lines.append("")
        }
        table("must_keep failures", keep.filter { !$0.passed })
        table("must_fix failures", attempted.filter { !$0.passed })
        table("Fixed", attempted.filter(\.passed))
        table("Left alone by design", byDesign)
        return lines.joined(separator: "\n")
    }

    private static func cell(_ text: String) -> String {
        text.replacingOccurrences(of: "|", with: "\\|")
    }
}

/// Scoring against `expected_smart` (`docs/plans/v0.4.md` §4.2).
public enum SmartScore {
    /// Smart has to get at least this many more target cases right than Light.
    public static let marginOverLight = 10

    public static func alternatives(_ expected: String) -> [String] {
        expected.components(separatedBy: " || ").filter { !$0.isEmpty }
    }

    /// The cases the "better than Light" count is over: what Smart is meant to fix, without the ones judged for meaning only.
    public static func isTarget(_ testCase: CleanupEval.Case) -> Bool {
        ["must_fix", "smart_fix"].contains(testCase.category) && !testCase.notes.contains("smart: meaning only")
            && !testCase.expectedSmart.isEmpty
    }

    public static func matches(_ output: String, _ testCase: CleanupEval.Case) -> Bool {
        alternatives(testCase.expectedSmart).contains(output)
    }
}
