/// Types text into whatever app is focused: put it on the clipboard, send ⌘V, then put the
/// user's previous clipboard back. Needs the Accessibility permission to post key events.
@MainActor
enum TextInserter {
    enum Outcome {
        case pasted
        /// Couldn't paste, so the text was left on the clipboard.
        case copied(Reason)

        /// For the history record.
        var recordName: String {
            switch self {
            case .pasted: "pasted"
            case .copied(.passwordField): "copied.passwordField"
            case .copied(.noTextField): "copied.noTextField"
            case .copied(.noAccessibility): "copied.noAccessibility"
            }
        }

        enum Reason {
            case passwordField, noTextField, noAccessibility

            var message: String {
                switch self {
                case .passwordField: "Password field · Copied, press ⌘V"
                case .noTextField: "No text field · Copied, press ⌘V"
                case .noAccessibility: "Copied · press ⌘V (Accessibility is off)"
                }
            }
        }
    }

    /// How long to wait before restoring the clipboard. Slow apps read the paste late.
    static let restoreDelay: Duration = .milliseconds(300)
    /// Clipboard history apps skip content marked with these (nspasteboard.org).
    private static let transientTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Tells whether a key was pressed since the last paste, for fields Accessibility can't read.
    static weak var keyboard: HotkeyMonitor?
    private static var lastPaste: (appBundleID: String?, date: Date)?
    /// When the last ⌘V was sent: the end of the wait the person feels. The clipboard restore after it isn't waiting.
    static private(set) var lastSentAt: Date?
    /// Where the last paste went, for `PasteWatcher`. Taken once.
    private static var lastTarget: PasteWatcher.Target?

    static func takeLastTarget() -> PasteWatcher.Target? {
        defer { lastTarget = nil }
        return lastTarget
    }

    /// - Parameter language: Whisper code of the text's language, which decides on a leading space.
    static func insert(_ text: String, language: String) async -> Outcome {
        let pasteboard = NSPasteboard.general
        // Another paste changes the field, so the watch on the last one ends here.
        PasteWatcher.shared.finish(.nextDictation)
        lastTarget = nil

        if let reason = reasonNotToPaste() {
            copy(text)
            return .copied(reason)
        }

        let spaced = needsLeadingSpace(text, language: language) ? " " + text : text
        let saved = snapshot(pasteboard)
        writeTransient(spaced, to: pasteboard)
        let ourChange = pasteboard.changeCount

        let element = FocusedField.element()
        sendCommandV()
        lastSentAt = Date()
        let app = NSWorkspace.shared.frontmostApplication
        lastPaste = (app?.bundleIdentifier, Date())
        if let element, let app {
            lastTarget = PasteWatcher.Target(element: element, pid: app.processIdentifier, pasted: spaced)
        }
        _ = keyboard?.takeKeyPressed()
        try? await Task.sleep(for: restoreDelay)

        // Only restore if nothing else touched the clipboard in the meantime.
        if pasteboard.changeCount == ourChange {
            restore(saved, to: pasteboard)
        }
        return .pasted
    }

    private static func needsLeadingSpace(_ text: String, language: String) -> Bool {
        let context: InsertionSpacing.Context
        if case .readable(let before) = FocusedField.textBeforeCaret() {
            context = .readable(before: before)
        } else {
            let keyPressed = keyboard?.takeKeyPressed() ?? true
            context = .unreadable(previousDictation: lastPaste.map {
                InsertionSpacing.PreviousDictation(
                    isSameApp: $0.appBundleID == NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
                    secondsAgo: Date().timeIntervalSince($0.date),
                    keyPressedSince: keyPressed
                )
            })
        }
        return InsertionSpacing.needsLeadingSpace(newText: text, language: language, context: context)
    }

    /// The copy-only path stays a normal copy, since the user wants that one kept.
    private static func writeTransient(_ text: String, to pasteboard: NSPasteboard) {
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in transientTypes {
            item.setData(Data(), forType: type)
        }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
    }

    private static func reasonNotToPaste() -> Outcome.Reason? {
        guard AXIsProcessTrusted() else { return .noAccessibility }
        if IsSecureEventInputEnabled() { return .passwordField }
        switch FocusedField.current() {
        case .text: return nil
        case .secure: return .passwordField
        case .none: return .noTextField
        }
    }

    static func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    private static func sendCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let vKey = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        for event in [down, up] {
            event?.flags = .maskCommand
            event?.setIntegerValueField(.eventSourceUserData, value: HotkeyMonitor.syntheticEventTag)
        }
        down?.post(tap: .cgAnnotatedSessionEventTap)
        up?.post(tap: .cgAnnotatedSessionEventTap)
    }

    private static func snapshot(_ pasteboard: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            var data: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                data[type] = item.data(forType: type)
            }
            return data
        }
    }

    private static func restore(_ items: [[NSPasteboard.PasteboardType: Data]], to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let restored = items.map { entries -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in entries {
                item.setData(data, forType: type)
            }
            return item
        }
        if !restored.isEmpty {
            pasteboard.writeObjects(restored)
        }
    }
}

/// Reads the focused UI element through Accessibility.
enum FocusedField {
    private static let log = Logger(subsystem: "com.localflow.app", category: "insertion")

    /// What kind of place the focused element is. `FocusClassifier` decides.
    static func current() -> FocusClassifier.Kind {
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.25)
        var focused: CFTypeRef?
        let error = AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused)
        if error == .noValue { return .none }
        guard error == .success, let focused else { return .text }
        let element = focused as! AXUIElement

        func hasValue(_ attribute: String) -> Bool {
            var value: CFTypeRef?
            return AXUIElementCopyAttributeValue(element, attribute as CFString, &value) == .success && value != nil
        }
        var role: CFTypeRef?
        AXUIElementCopyAttributeValue(element, kAXRoleAttribute as CFString, &role)
        var settable = DarwinBoolean(false)
        AXUIElementIsAttributeSettable(element, kAXValueAttribute as CFString, &settable)
        let description = FocusClassifier.Element(
            role: role as? String,
            subrole: subrole(of: element),
            isValueSettable: settable.boolValue,
            hasSelectedRange: hasValue(kAXSelectedTextRangeAttribute),
            hasEditableAncestor: hasValue("AXEditableAncestor"),
            isWebContent: hasValue("AXSelectedTextMarkerRange")
        )
        let kind = FocusClassifier.classify(description)
        // For reports of a check with nothing pasted (docs/known-issues.md). Never any text.
        log.debug("app=\(NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? "?", privacy: .public) role=\(description.role ?? "nil", privacy: .public) subrole=\(description.subrole ?? "nil", privacy: .public) editable=\(description.hasEditableAncestor, privacy: .public) web=\(description.isWebContent, privacy: .public) settable=\(description.isValueSettable, privacy: .public) range=\(description.hasSelectedRange, privacy: .public) -> \(String(describing: kind), privacy: .public)")
        return kind
    }

    enum Caret {
        case readable(before: Character)
        case unreadable
    }

    /// Reads one character before the caret. Nothing is kept: it only decides on a space.
    static func textBeforeCaret() -> Caret {
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.25)
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused else { return .unreadable }
        let element = focused as! AXUIElement
        AXUIElementSetMessagingTimeout(element, 0.25)

        var rangeValue: CFTypeRef?
        var selection = CFRange()
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &rangeValue) == .success,
              let rangeValue, AXValueGetValue(rangeValue as! AXValue, .cfRange, &selection),
              selection.location != kCFNotFound else { return .unreadable }
        // Terminals such as cmux always report 0, so it can't be taken to mean the start of the field.
        guard selection.location > 0 else { return .unreadable }

        var previous = CFRange(location: selection.location - 1, length: 1)
        var text: CFTypeRef?
        if let parameter = AXValueCreate(.cfRange, &previous),
           AXUIElementCopyParameterizedAttributeValue(
               element, kAXStringForRangeParameterizedAttribute as CFString, parameter, &text
           ) == .success,
           let character = (text as? String)?.last {
            return .readable(before: character)
        }
        // Some fields only offer their whole value.
        var value: CFTypeRef?
        if AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &value) == .success,
           let units = (value as? String)?.utf16, selection.location <= units.count {
            let end = units.index(units.startIndex, offsetBy: selection.location)
            if let character = String(decoding: units[..<end], as: UTF16.self).last {
                return .readable(before: character)
            }
        }
        return .unreadable
    }

    /// The focused element, if Accessibility gives one.
    static func element() -> AXUIElement? {
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.25)
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return nil }
        let element = focused as! AXUIElement
        AXUIElementSetMessagingTimeout(element, 0.25)
        return element
    }

    /// The element's whole text, for `PasteWatcher` to follow the pasted span. Never logged or stored.
    static func value(of element: AXUIElement) -> String? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &value) == .success else { return nil }
        return value as? String
    }

    /// The caret, as a UTF-16 offset. Nil if unknown, or 0, which terminals such as cmux always report.
    static func caret(of element: AXUIElement) -> Int? {
        var rangeValue: CFTypeRef?
        var selection = CFRange()
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &rangeValue) == .success,
              let rangeValue, AXValueGetValue(rangeValue as! AXValue, .cfRange, &selection),
              selection.location != kCFNotFound, selection.location > 0 else { return nil }
        return selection.location
    }

    private static func subrole(of element: AXUIElement) -> String? {
        var value: CFTypeRef?
        AXUIElementCopyAttributeValue(element, kAXSubroleAttribute as CFString, &value)
        return value as? String
    }
}
