#!/usr/bin/env python3
"""Score language-choice rules on bench/lideval output (v1.1). No model runs here: every rule picks between text already made.

Usage: bench/.venv/bin/python -I bench/lid_score.py [runs.jsonl ...]   (default: every bench/data/runs/*.jsonl but smoke)
Writes bench/lid_results.md.

What a rule decides: run Whisper fixed to English (no prompt), or fixed to the second language with its mixed prompt.
That is the app's only real choice. Then the app's safety net: second language chosen, the language has its own script,
and the text has none of it → the run without the prompt (as Transcriber does).

Error: character error rate after lowercasing and dropping spaces and punctuation, so it works the same for every script.
HiKE lists loanwords; either spelling counts (the Korean one is mapped to the English one in both texts).
Severe: error over 50%, meaning most of what was said is gone or changed. That is the failure this work is about.
"""
import json
import math
import re
import sys
import unicodedata
from collections import defaultdict
from pathlib import Path

BENCH = Path(__file__).resolve().parent
DATA = BENCH / "data"

SCRIPTS = {"ko": r"[가-힣]", "ja": r"[぀-ヿ一-鿿]", "zh": r"[一-鿿]", "hi": r"[ऀ-ॿ]"}


def normalize(text, loanwords=()):
    text = unicodedata.normalize("NFKC", text).lower()
    for pair in loanwords:
        text = text.replace(pair["Korean"], pair["English"].lower())
    return "".join(ch for ch in text if ch.isalnum())


def cer(ref, hyp):
    if not ref:
        return 0.0 if not hyp else 1.0
    prev = list(range(len(hyp) + 1))
    for i, r in enumerate(ref, 1):
        cur = [i] + [0] * len(hyp)
        for j, h in enumerate(hyp, 1):
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (r != h))
        prev = cur
    return min(prev[-1] / len(ref), 1.0)


def load():
    meta = {}
    for path in (DATA / "manifests").glob("*.jsonl"):
        for line in path.read_text().splitlines():
            row = json.loads(line)
            meta[row["id"]] = row
    files = [Path(p) for p in sys.argv[1:]] or [p for p in (DATA / "runs").glob("*.jsonl") if p.stem != "smoke"]
    clips = []
    for path in files:
        for line in path.read_text().splitlines():
            run = json.loads(line)
            if run["id"] in meta:
                clips.append({**meta[run["id"]], **run})
    return clips


def text_for(clip, choose_l2):
    if not choose_l2:
        return clip["forcedEN"]["text"]
    text = clip["forcedL2Prompt"]["text"]
    script = SCRIPTS.get(clip["l2"])
    if script and text and not re.search(script, text):
        return clip["forcedL2NoPrompt"]["text"]
    return text


def margin(score):  # how much more English than the second language, in log probability
    return score["en"] - score["l2"]


# Each rule: clip → True when it picks the second language. Cost: extra encoder passes beyond the app's one detection.
def rules(taus=(0, 1, 2, 3, 4, 6)):
    out = {
        "app today (higher of the two)": (lambda c: c["whole"]["l2"] > c["whole"]["en"], lambda c: 0),
        "always English": (lambda c: False, lambda c: 0),
        "always second language": (lambda c: True, lambda c: 0),
    }
    for tau in taus:
        out[f"English only if whole margin > {tau}"] = (lambda c, t=tau: margin(c["whole"]) <= t, lambda c: 0)
    for tau in taus:
        out[f"English only if whole and every 4 s window margin > {tau}"] = (
            lambda c, t=tau: margin(c["whole"]) <= t or any(margin(w) <= t for w in c["windows"]),
            lambda c: len(c["windows"]),
        )
    return out


def main():
    clips = load()
    if not clips:
        sys.exit("no runs yet")
    for c in clips:
        loan = c.get("loanwords") or ()
        ref = normalize(c["reference"], loan)
        c["err"] = {False: cer(ref, normalize(text_for(c, False), loan)), True: cer(ref, normalize(text_for(c, True), loan))}

    groups = defaultdict(list)
    for c in clips:
        groups[(c["source"], c["kind"], c["l2"])].append(c)

    lines = ["# Language choice (v1.1)", "",
             "Generated by `bench/lid_score.py` from `bench/lideval` runs on public data (no owner recordings). "
             "Error is character error rate without spaces and punctuation; severe means over 50%.", ""]
    lines += ["## Clips", "", "| source | kind | second language | clips |", "|---|---|---|---|"]
    for key in sorted(groups):
        lines.append(f"| {key[0]} | {key[1]} | {key[2]} | {len(groups[key])} |")

    kinds = sorted({k[1] for k in groups})
    lines += ["", "## Rules, by kind of speech", "",
              "Each cell: mean error / severe share. Extra encoder passes are on top of today's one detection (about 0.1–0.4 s each).", "",
              "| rule | " + " | ".join(kinds) + " | extra passes (mean) |", "|---|" + "---|" * (len(kinds) + 1)]
    for name, (pick, cost) in rules().items():
        cells = []
        for kind in kinds:
            subset = [c for c in clips if c["kind"] == kind]
            errs = [c["err"][pick(c)] for c in subset]
            cells.append(f"{sum(errs) / len(errs):.1%} / {sum(e > 0.5 for e in errs) / len(errs):.1%}")
        mean_cost = sum(cost(c) for c in clips) / len(clips)
        lines.append(f"| {name} | " + " | ".join(cells) + f" | {mean_cost:.1f} |")
    best = [min(c["err"].values()) for c in clips]
    lines += ["", f"Best of the two for every clip (no rule can beat this): {sum(best) / len(best):.1%} mean error."]

    by_lang = sorted({c["l2"] for c in clips})
    lines += ["", "## App today vs. the simplest change, by second language", "",
              "| second language | kind | clips | today | English only if margin > 2 | always second language |", "|---|---|---|---|---|---|"]
    r = rules()
    for lang in by_lang:
        for kind in kinds:
            subset = [c for c in clips if c["l2"] == lang and c["kind"] == kind]
            if not subset:
                continue
            row = []
            for name in ["app today (higher of the two)", "English only if whole margin > 2", "always second language"]:
                errs = [c["err"][r[name][0](c)] for c in subset]
                row.append(f"{sum(errs) / len(errs):.1%} / {sum(e > 0.5 for e in errs) / len(errs):.1%}")
            lines.append(f"| {lang} | {kind} | {len(subset)} | " + " | ".join(row) + " |")

    (BENCH / "lid_results.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
